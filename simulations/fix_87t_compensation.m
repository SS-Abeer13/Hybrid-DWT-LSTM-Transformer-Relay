function fix_87t_compensation(saveChanges)
%FIX_87T_COMPENSATION Correct the conventional 87T path calibration in 'Yd1 Compensation' (2026-10-20).
%
% Plant facts (ground truth from the V-I measurement blocks, simulations/probe_ct_truth.m, 2026-10-21):
%   * Step_down_Transformer 300 MVA, 230 kV Y / 11 kV Delta (D1)  -> rated line currents 753.06 A / 15745.9 A.
%   * The CT subsystems behave as HV 809.6:1 and LV 16925:1 (2.024 x their winding-voltage ratios 400:1 and 92000/11:1; true line
%     current / CT-secondary current measured at two loads, spread < 0.05 %). Rated CT-secondary current = 0.9302 A on BOTH sides.
%     (History: the original chart assumed HV 400:1 -> 1.883 A and LV 18400:1 -> 0.8557 A; the first correction on 2026-10-20 used
%     1.8827 A / 1.8827 A from the winding voltages, which was still 2.024 x too large.)
%   * Healthy traces obey  LV_amps = (1/sqrt3)*[1 0 -1; -1 1 0; 0 -1 1] * HV_amps  (residual ~2 % of load).
%     The chart applied the TRANSPOSE of this matrix to the HV side.
% The 87T settings (pickup 0.30, slopes 0.25/0.60, breakpoint 3.0, high-set 10.0) are NOT changed.
% The LSTM input path (Yd1_plant_map / I_diff_LSTM) is independent of this chart.
%
%   fix_87t_compensation        % apply to the loaded model only
%   fix_87t_compensation(true)  % apply and save

if nargin < 1, saveChanges = false; end
model = 'TransformerWithCTSaturation';
thisDir = fileparts(mfilename('fullpath'));
if ~bdIsLoaded(model), load_system(fullfile(thisDir, [model '.slx'])); end

charts = sfroot().find('-isa', 'Stateflow.EMChart');
hit = [];
for c = charts(:).'
    if contains(c.Script, 'function [I_hv_comp_pu, I_lv_comp_pu] = Yd1_Compensation')
        hit = c;
    end
end
assert(~isempty(hit), 'Yd1_Compensation chart not found');

newScript = strjoin({ ...
'function [I_hv_comp_pu, I_lv_comp_pu] = Yd1_Compensation(I_hv_sec, I_lv_sec)', ...
'% =========================================================================', ...
'% HYBRID ADAPTIVE 87T RELAY: SIGNAL CONDITIONING & COMPENSATION', ...
'% Vector Group: Yd1 (HV Wye, LV Delta). CORRECTED 2026-10-20 (see fix_87t_compensation.m)', ...
'% =========================================================================', ...
'    % 1. NAMEPLATE RATINGS (300 MVA)', ...
'    S_nom   = 300e6;', ...
'    V_hv_ll = 230e3;', ...
'    V_lv_ll = 11e3;', ...
'', ...
'    % 2. Primary full-load amperes', ...
'    I_FLA_hv = S_nom / (sqrt(3) * V_hv_ll);   % 753.06 A', ...
'    I_FLA_lv = S_nom / (sqrt(3) * V_lv_ll);   % 15745.9 A', ...
'', ...
'    % 3. EFFECTIVE CT ratios measured against the true line currents (2.024 x the winding-voltage ratios 400 and 92000/11)', ...
'    CT_Ratio_HV = 809.6;', ...
'    CT_Ratio_LV = 16925;', ...
'', ...
'    % 4. Rated secondary currents = 1.0 pu bases (0.9302 A on both sides)', ...
'    I_nom_hv = I_FLA_hv / CT_Ratio_HV;', ...
'    I_nom_lv = I_FLA_lv / CT_Ratio_LV;', ...
'', ...
'    % 5. Per-unit normalisation', ...
'    I_hv_pu = I_hv_sec ./ I_nom_hv;', ...
'    I_lv_pu = I_lv_sec ./ I_nom_lv;', ...
'', ...
'    % 6. Yd1 compensation of the Wye (HV) side. This is the mapping the plant obeys:', ...
'    %    I_lv = M * I_hv for healthy operation (verified on simulated traces, residual ~2 percent).', ...
'    M_Yd1 = (1/sqrt(3)) * [ 1,  0, -1; ', ...
'                           -1,  1,  0; ', ...
'                            0, -1,  1];', ...
'    I_hv_comp_pu = M_Yd1 * I_hv_pu;', ...
'', ...
'    % LV (Delta) side passes through', ...
'    I_lv_comp_pu = I_lv_pu;', ...
'end'}, newline);
hit.Script = newScript;

% sanity: evaluate the new constants and the mapping on a balanced load
S = 300e6; Ihv = S/(sqrt(3)*230e3)/809.6; Ilv = S/(sqrt(3)*11e3)/16925;
assert(abs(Ihv - 0.9302) < 1e-3 && abs(Ilv - 0.9302) < 1e-3, 'bases are not 0.9302 A');
M = (1/sqrt(3)) * [1 0 -1; -1 1 0; 0 -1 1];
a = 2*pi/3; ihv = cos([0 -a a].' );               % balanced HV phase currents
assert(abs(norm(M*ihv) - norm(ihv)) < 1e-9, 'compensation must preserve balanced magnitude');
fprintf('Yd1 Compensation corrected: bases HV %.4f A / LV %.4f A, matrix transposed to the plant mapping.\n', Ihv, Ilv);

if saveChanges
    save_system(model);
    fprintf('Saved %s.\n', model);
else
    fprintf('Applied to the loaded model only (not saved).\n');
end
end
