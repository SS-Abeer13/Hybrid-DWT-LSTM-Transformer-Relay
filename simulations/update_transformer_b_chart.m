function update_transformer_b_chart()
% UPDATE_TRANSFORMER_B_CHART Updates the compensation chart in TransformerB_v4.slx
% with the calibrated base current (0.8232 A) and validated Dyn11 matrix (M2).

thisDir = fileparts(mfilename('fullpath'));
model = 'TransformerB_v4';
slxPath = fullfile(thisDir, [model '.slx']);

fprintf('Updating compensation chart in %s...\n', slxPath);

if ~bdIsLoaded(model)
    load_system(slxPath);
end

charts = sfroot().find('-isa', 'Stateflow.EMChart');
hit = [];
for c = charts(:).'
    if contains(c.Path, model) && (contains(c.Script, 'Compensation') || contains(c.Path, 'Compensation'))
        hit = c;
        break;
    end
end
assert(~isempty(hit), 'Compensation chart not found in %s', model);

newScript = strjoin({ ...
'function [I_hv_comp_pu, I_lv_comp_pu] = Yd1_Compensation(I_hv_sec, I_lv_sec)', ...
'% =========================================================================', ...
'% HYBRID ADAPTIVE 87T RELAY: SIGNAL CONDITIONING & COMPENSATION (Plant B)', ...
'% Vector Group: Dyn11 (HV Delta, LV Wye). 40 MVA, 132/33 kV, 1 A secondaries', ...
'% Calibrated: 2026-10-27 from probe_ct_truth_plant_b.m', ...
'% =========================================================================', ...
'    % 1. NAMEPLATE RATINGS (40 MVA)', ...
'    S_nom   = 40e6;', ...
'    V_hv_ll = 132e3;', ...
'    V_lv_ll = 33e3;', ...
'', ...
'    % 2. Primary full-load amperes', ...
'    I_FLA_hv = S_nom / (sqrt(3) * V_hv_ll);   % 174.9546 A', ...
'    I_FLA_lv = S_nom / (sqrt(3) * V_lv_ll);   % 699.8184 A', ...
'', ...
'    % 3. EFFECTIVE CT ratios', ...
'    CT_Ratio_HV = 202.0119;', ...
'    CT_Ratio_LV = 808.8849;', ...
'', ...
'    % 4. Rated secondary currents = 1.0 pu bases (Mean: 0.8232 A)', ...
'    I_nom = 0.8232;', ...
'', ...
'    % 5. Per-unit normalisation', ...
'    I_hv_pu = I_hv_sec ./ I_nom;', ...
'    I_lv_pu = I_lv_sec ./ I_nom;', ...
'', ...
'    % 6. Dyn11 compensation of the Wye (LV) side.', ...
'    % M2 matrix yields 0.0353 pu residual (pure magnetizing current).', ...
'    M_Dyn11 = (1/sqrt(3)) * [ 1, -1,  0; ', ...
'                              0,  1, -1; ', ...
'                             -1,  0,  1];', ...
'    I_lv_comp_pu = M_Dyn11 * I_lv_pu;', ...
'', ...
'    % HV (Delta) side passes through', ...
'    I_hv_comp_pu = I_hv_pu;', ...
'end'}, newline);

hit.Script = newScript;

save_system(model);
fprintf('Updated and saved %s successfully.\n', model);

setappdata(0, 'HybridRelaySkipLSTM', true);
set_param(model, 'SimulationCommand', 'update');
fprintf('Model diagram compiled successfully with Dyn11 compensation!\n');

close_system(model, 0);
end
