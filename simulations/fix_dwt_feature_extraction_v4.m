function fix_dwt_feature_extraction_v4(saveChanges)
%FIX_DWT_FEATURE_EXTRACTION_V4 Normalise LSTM input to per-unit in Simulink chart.
%
% Implements Step 1.4: divide plant-compensated differential by rated secondary
% current (1.8610 A) before feature extraction (wavelet decomposition & FFT).

if nargin < 1, saveChanges = true; end
model = 'TransformerWithCTSaturation_v4';
thisDir = fileparts(mfilename('fullpath'));
if ~bdIsLoaded(model), load_system(fullfile(thisDir, [model '.slx'])); end

charts = sfroot().find('-isa', 'Stateflow.EMChart');
hit = [];
for c = charts(:).'
    if contains(c.Path, model) && contains(c.Script, 'function features = DWT_Feature_Extraction')
        hit = c;
        break;
    end
end
assert(~isempty(hit), 'DWT_Feature_Extraction chart not found in %s', model);

newScript = strjoin({ ...
'function features = DWT_Feature_Extraction(I_diff_window)', ...
'    % Inputs: I_diff_window (32x3 matrix from the Buffer block)', ...
'    % Outputs: features (1x12 vector for the LSTM)', ...
'    % Step 1.4: Normalised to per-unit using rated secondary current (1.8610 A)', ...
'    ', ...
'    % wavelets and fft are extrinsic because code generator does not support dwt/wavedec/fft', ...
'    coder.extrinsic(''wavedec'', ''detcoef'', ''appcoef'', ''fft'');', ...
'    ', ...
'    features = zeros(1, 12);', ...
'    I_base = 1.8610; % rated CT-secondary base current for v4 (probe_ct_truth_v4.m)', ...
'    ', ...
'    for ph = 1:3', ...
'        signal = I_diff_window(:, ph) / I_base;', ...
'        ', ...
'        % Pre-initialize variables for code generation compliance', ...
'        C = zeros(45, 1);', ...
'        L = zeros(4, 1);', ...
'        d1 = zeros(19, 1);', ...
'        d2 = zeros(13, 1);', ...
'        a2 = zeros(13, 1);', ...
'        fft_vals = zeros(32, 1);', ...
'        ', ...
'        % 2-level db4 wavelet decomposition', ...
'        [C, L] = wavedec(signal, 2, ''db4'');', ...
'        ', ...
'        % Calculate squared DWT energy coefficients', ...
'        d1 = detcoef(C, L, 1);', ...
'        d2 = detcoef(C, L, 2);', ...
'        a2 = appcoef(C, L, ''db4'', 2);', ...
'        ', ...
'        E_D1 = sum(d1.^2);', ...
'        E_D2 = sum(d2.^2);', ...
'        E_A2 = sum(a2.^2);', ...
'        ', ...
'        % Store features in 12-element feature vector', ...
'        base = (ph - 1) * 3 + 1;', ...
'        features(base)     = log(1 + E_D1);', ...
'        features(base + 1) = log(1 + E_D2);', ...
'        features(base + 2) = log(1 + E_A2);', ...
'        ', ...
'        % 2nd Harmonic Ratio (Bin 3 = 100 Hz, Bin 2 = 50 Hz @ 1600 Hz / 32 samples)', ...
'        fft_vals = abs(fft(signal));', ...
'        ratio_2nd = fft_vals(3) / (fft_vals(2) + 1e-4);', ...
'        features(9 + ph) = min(ratio_2nd, 2.0);', ...
'    end', ...
'end'}, newline);

hit.Script = newScript;
fprintf('DWT_Feature_Extraction chart updated with I_base = 1.8610 A per-unit normalisation.\n');

if saveChanges
    save_system(model);
    fprintf('Saved %s.\n', model);
end
end
