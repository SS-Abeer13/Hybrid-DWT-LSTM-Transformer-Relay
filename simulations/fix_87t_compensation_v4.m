function fix_87t_compensation_v4(saveChanges)
%FIX_87T_COMPENSATION_V4 Set calibrated v4 parameters in 'Yd1 Compensation' chart.
%
% Plant parameters (measured 2026-10-26 in simulations/probe_ct_truth_v4.m):
%   * 300 MVA, 230 kV / 11 kV, Yd1
%   * Effective CT Ratios: HV 404.7288 : 1, LV 8460.0372 : 1
%   * Rated Secondary Currents: HV 1.8607 A, LV 1.8612 A (~1.8610 A)
%   * Matrix: M_Yd1 = (1/sqrt(3)) * [1 0 -1; -1 1 0; 0 -1 1]

if nargin < 1, saveChanges = true; end
model = 'TransformerWithCTSaturation_v4';
thisDir = fileparts(mfilename('fullpath'));
if ~bdIsLoaded(model), load_system(fullfile(thisDir, [model '.slx'])); end

charts = sfroot().find('-isa', 'Stateflow.EMChart');
hit = [];
for c = charts(:).'
    if contains(c.Path, model) && contains(c.Script, 'function [I_hv_comp_pu, I_lv_comp_pu] = Yd1_Compensation')
        hit = c;
        break;
    end
end
assert(~isempty(hit), 'Yd1_Compensation chart not found in %s', model);

newScript = strjoin({ ...
'function [I_hv_comp_pu, I_lv_comp_pu] = Yd1_Compensation(I_hv_sec, I_lv_sec)', ...
'% =========================================================================', ...
'% HYBRID ADAPTIVE 87T RELAY: SIGNAL CONDITIONING & COMPENSATION (v4)', ...
'% Vector Group: Yd1 (HV Wye, LV Delta). Calibrated 2026-10-26 (series CT wiring)', ...
'% =========================================================================', ...
'    % 1. NAMEPLATE RATINGS (300 MVA)', ...
'    S_nom   = 300e6;', ...
'    V_hv_ll = 230e3;', ...
'    V_lv_ll = 11e3;', ...
'', ...
'    % 2. Primary full-load amperes', ...
'    I_FLA_hv = S_nom / (sqrt(3) * V_hv_ll);   % 753.064 A', ...
'    I_FLA_lv = S_nom / (sqrt(3) * V_lv_ll);   % 15745.916 A', ...
'', ...
'    % 3. EFFECTIVE CT ratios measured against the true line currents (series CT wiring)', ...
'    CT_Ratio_HV = 404.7288;', ...
'    CT_Ratio_LV = 8460.0372;', ...
'', ...
'    % 4. Rated secondary currents = 1.0 pu bases (1.8607 A HV / 1.8612 A LV)', ...
'    I_nom_hv = I_FLA_hv / CT_Ratio_HV;', ...
'    I_nom_lv = I_FLA_lv / CT_Ratio_LV;', ...
'', ...
'    % 5. Per-unit normalisation', ...
'    I_hv_pu = I_hv_sec ./ I_nom_hv;', ...
'    I_lv_pu = I_lv_sec ./ I_nom_lv;', ...
'', ...
'    % 6. Yd1 compensation of the Wye (HV) side. Mapping: I_lv = M * I_hv for healthy operation.', ...
'    M_Yd1 = (1/sqrt(3)) * [ 1,  0, -1; ', ...
'                           -1,  1,  0; ', ...
'                            0, -1,  1];', ...
'    I_hv_comp_pu = M_Yd1 * I_hv_pu;', ...
'', ...
'    % LV (Delta) side passes through', ...
'    I_lv_comp_pu = I_lv_pu;', ...
'end'}, newline);
hit.Script = newScript;

% verify on balanced load
S = 300e6; Ihv = S/(sqrt(3)*230e3)/404.7288; Ilv = S/(sqrt(3)*11e3)/8460.0372;
assert(abs(Ihv - 1.8607) < 1e-3 && abs(Ilv - 1.8612) < 1e-3, 'bases are not ~1.861 A');
fprintf('Yd1 Compensation v4 set: bases HV %.4f A / LV %.4f A.\n', Ihv, Ilv);

if saveChanges
    save_system(model);
    fprintf('Saved %s.\n', model);
end
end
