% apply_calibration_fix.m
% Update Yd1_Compensation script in the model to set CT_Ratio_LV = 92000/5.

try
    model = 'TransformerWithCTSaturation';
    if ~bdIsLoaded(model)
        load_system(model);
    end
    
    subsys = [model '/Hybrid 87T Relay'];
    comp_block = [subsys '/Yd1 Compensation'];
    
    % Find Stateflow Chart object for Yd1 Compensation
    rt = sfroot;
    chart = rt.find('-isa', 'Stateflow.EMChart', 'Path', comp_block);
    if isempty(chart)
        error('Yd1 Compensation chart not found!');
    end
    
    % Update the script with CT_Ratio_LV = 92000 / 5
    new_script = sprintf([ ...
        'function [I_hv_comp_pu, I_lv_comp_pu] = Yd1_Compensation(I_hv_sec, I_lv_sec)\n' ...
        '%% =========================================================================\n' ...
        '%% HYBRID ADAPTIVE 87T RELAY: SIGNAL CONDITIONING & COMPENSATION\n' ...
        '%% Vector Group: Yd1 (HV Wye, LV Delta - Delta lags by 30 degrees)\n' ...
        '%% =========================================================================\n' ...
        '    %% 1. RIGID NAMEPLATE RATINGS (300 MVA Base)\n' ...
        '    S_nom   = 300e6;       %% 300 MVA\n' ...
        '    V_hv_ll = 230e3;       %% 230 kV Line-to-Line Primary\n' ...
        '    V_lv_ll = 11e3;        %% 11 kV Line-to-Line Secondary\n' ...
        '    \n' ...
        '    %% 2. Calculate Primary Full Load Amperes (FLA)\n' ...
        '    I_FLA_hv = S_nom / (sqrt(3) * V_hv_ll); %% ~753.06 A\n' ...
        '    I_FLA_lv = S_nom / (sqrt(3) * V_lv_ll); %% ~15745.92 A\n' ...
        '    \n' ...
        '    %% 3. Hardware Current Transformer (CT) Ratios [2000/5 A and 92000/5 A]\n' ...
        '    CT_Ratio_HV = 2000 / 5;   %% CTR_HV = 400\n' ...
        '    CT_Ratio_LV = 92000 / 5;  %% CTR_LV = 18400 (Fixed calibration mismatch)\n' ...
        '    \n' ...
        '    %% 4. True Nominal Secondary Currents (The absolute 1.0 p.u. bases)\n' ...
        '    I_nom_hv = I_FLA_hv / CT_Ratio_HV; %% ~1.8827 A\n' ...
        '    I_nom_lv = I_FLA_lv / CT_Ratio_LV; %% ~0.8557 A (Correct base for 92000/5 CT)\n' ...
        '\n' ...
        '    %% 5. PER-UNIT NORMALIZATION\n' ...
        '    I_hv_pu = I_hv_sec ./ I_nom_hv;\n' ...
        '    I_lv_pu = I_lv_sec ./ I_nom_lv;\n' ...
        '\n' ...
        '    %% 6. Yd1 VECTOR GROUP COMPENSATION MATRIX\n' ...
        '    M_Yd1 = (1/sqrt(3)) * [ 1, -1,  0; \n' ...
        '                            0,  1, -1; \n' ...
        '                           -1,  0,  1 ];\n' ...
        '                       \n' ...
        '    %% Apply compensation to the Wye (HV) side\n' ...
        '    I_hv_comp_pu = M_Yd1 * I_hv_pu;\n' ...
        '    \n' ...
        '    %% Pass through the LV side (Delta natively traps zero sequence)\n' ...
        '    I_lv_comp_pu = I_lv_pu;\n' ...
        'end' ...
    ]);
    
    chart.Script = new_script;
    save_system(model);
    fprintf('✓ Yd1 Compensation block updated and saved.\n');
    
catch ME
    disp(['Error: ' ME.message]);
    disp(ME.getReport());
end
